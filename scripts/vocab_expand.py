# Filter bad entries
def clean(pairs, pos, theme, cefr):
    out = []
    for ru, he in pairs:
        ru = ru.strip()
        he = he.strip()
        if not ru or not he or he == "x" or len(ru) < 2:
            continue
        if any(ord(c) > 1000 and not ('а' <= c.lower() <= 'я' or c in 'ёЁ') for c in ru if not c.isascii()):
            # keep cyrillic only for ru — skip if has CJK etc
            if any('\u4e00' <= c <= '\u9fff' for c in ru):
                continue
        out.append((ru, he, pos, theme, cefr))
    return out

