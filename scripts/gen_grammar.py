import json, pathlib

def lesson(id_, unit, titleHe, titleRu, tip, exercises, xp=12):
    return {
        "id": id_,
        "level": "GRAM",
        "unitId": unit,
        "titleHe": titleHe,
        "titleRu": titleRu,
        "xp": xp,
        "exercises": ([{"type": "listen_choice", "ru": tip[:0], "tip": tip, "choices": [{"he": "הבנתי", "correct": True}, {"he": "דלג", "correct": True}, {"he": "…", "correct": False}, {"he": "…", "correct": False}]} ] if False else []) + exercises,
        # tip attached to first ex instead:
    }

def with_tip(exs, tip):
    if exs and tip:
        exs[0] = dict(exs[0])
        exs[0]["tip"] = tip
    return exs

def fb(sentence, answer, options, he, tip=None):
    e = {"type": "fill_blank", "sentence": sentence, "answer": answer, "options": options, "he": he}
    if tip: e["tip"] = tip
    return e

def sb(he, words, distractors, ru=None, tip=None):
    e = {"type": "sentence_build", "he": he, "words": words, "distractors": distractors, "ru": ru or " ".join(words)}
    if tip: e["tip"] = tip
    return e

def lc(ru, correct_he, wrong, tip=None):
    ch = [{"he": correct_he, "correct": True}] + [{"he": w, "correct": False} for w in wrong]
    e = {"type": "listen_choice", "ru": ru, "choices": ch}
    if tip: e["tip"] = tip
    return e

