def build_all_lemmas():
    bags = [
        CORE_FUNCTION, A1_PEOPLE, A1_PLACES, A1_FOOD, A1_VERBS, A1_ADJ, A1_TIME, A1_NUM,
        A1_COLORS_CLOTHES, A1_BODY_HEALTH, A1_TRANSPORT, A1_WEATHER, A1_HOME, A1_HOBBIES,
        A2_EXTRA, B1_EXTRA, B2_EXTRA, C1_EXTRA, C2_EXTRA, EVERYDAY_EXTRA,
    ]
    seen = {}
    out = []
    for bag in bags:
        for item in bag:
            lem = item[0].strip().lower()
            if lem in seen or not lem or "dup" in item[1]:
                continue
            seen[lem] = True
            out.append({"lemma": item[0], "he": item[1], "pos": item[2], "theme": item[3], "cefr": item[4]})
    return out

class LemmaTracker:
    def __init__(self, bank=None):
        self.bank = bank or build_all_lemmas()
        self.by_lemma = {x["lemma"].lower(): x for x in self.bank}
        self.usage = defaultdict(int)
        self.introduced = set()

    def mark_text(self, ru_text):
        """Count lemma hits from a Russian string (simple tokenization)."""
        import re
        toks = re.findall(r"[А-Яа-яЁё\-]+", ru_text or "")
        for t in toks:
            low = t.lower()
            # try exact, then stem-ish strip endings lightly
            hit = None
            if low in self.by_lemma:
                hit = low
            else:
                for end in ("ами", "ями", "ого", "ему", "ому", "ыми", "ими", "ая", "яя", "ое", "ее",
                            "ые", "ие", "ую", "юю", "ой", "ей", "ом", "ем", "ах", "ях", "ов", "ев",
                            "ам", "ям", "у", "ю", "ы", "и", "а", "я", "е", "о"):
                    if len(low) > len(end) + 2 and low.endswith(end):
                        stem = low[:-len(end)]
                        for cand in (stem, stem + "а", stem + "ь", stem + "й", stem + "ть", stem + "ти"):
                            if cand in self.by_lemma:
                                hit = cand
                                break
                        if hit:
                            break
            if hit:
                self.usage[hit] += 1
                self.introduced.add(hit)

    def unused(self, cefr=None, theme=None, pos=None, limit=50):
        out = []
        for x in self.bank:
            key = x["lemma"].lower()
            if key in self.introduced and self.usage[key] >= 3:
                continue
            if cefr and x["cefr"] not in cefr:
                continue
            if theme and x["theme"] != theme:
                continue
            if pos and x["pos"] != pos:
                continue
            out.append(x)
            if len(out) >= limit:
                break
        # prefer never-used
        out.sort(key=lambda x: self.usage[x["lemma"].lower()])
        return out

    def pick(self, n, cefr=None, theme=None, pos=None):
        return self.unused(cefr=cefr, theme=theme, pos=pos, limit=n)

    def stats(self):
        return {
            "bank_size": len(self.bank),
            "introduced": len(self.introduced),
            "total_uses": sum(self.usage.values()),
        }

