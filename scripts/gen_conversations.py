"""Generate conversation scenarios JSON/JS for russian-learn."""
import json, pathlib

# Each scenario: id, level, titleHe, titleRu, settingHe, lines (npc/user turns),
# at user turns: choices (pick reply) + accepted (free answer variants)

def sc(id_, level, titleHe, titleRu, settingHe, steps):
    return {
        "id": id_,
        "level": level,
        "titleHe": titleHe,
        "titleRu": titleRu,
        "settingHe": settingHe,
        "steps": steps,
    }

def npc(ru, he=""):
    return {"speaker": "npc", "ru": ru, "he": he}

def user(promptHe, choices, accepted, model=None):
    """choices: list of {ru, he, ok}; accepted: list of ok Russian free answers"""
    return {
        "speaker": "user",
        "promptHe": promptHe,
        "choices": choices,
        "accepted": accepted,
        "model": model or (next((c["ru"] for c in choices if c.get("ok")), accepted[0] if accepted else "")),
    }

